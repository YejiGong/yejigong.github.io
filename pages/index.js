import Head from 'next/head'
import Image from 'next/image'
import styles from '../styles/Home.module.css'
import { useState } from 'react';
import Link from 'next/link';
import Information from './Information';
import Projects from './Projects';
import Etc from './Etc';

export default function Home() {
  const menus = ['Information', 'Projects', 'Etc'];
  const [selectedMenu, setSelectedMenu] = useState('Information');

  const handleMenuClick = (menu) => {
    setSelectedMenu(menu);
  }

  const renderContent = {Information: <Information/>, Projects:<Projects/>, Etc:<Etc/>}
  return (
    <div className={styles.container}>
      <Head>
        <title>Portfolio</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <div className={styles.main}>
        <div className={styles.mainTitle}>
          Portfolio
        </div>
        <div className={styles.menus}>
          {menus.map((menu, index) => (
            <div key={index} onClick={() => handleMenuClick(menu)}>
              {menu}
            </div>
          ))}
        </div>
      </div>
      <hr width="100%"/>
      <div className={styles.contents}>
        {selectedMenu && (
          <div>
              {selectedMenu && renderContent[selectedMenu]}
          </div>
        )}
      </div>
    </div>
  )
}
